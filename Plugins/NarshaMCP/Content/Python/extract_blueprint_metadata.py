#!/usr/bin/env python3
"""
Blueprint Metadata Extraction Helper

Executes the BlueprintMetadata Commandlet to extract Blueprint call graph data.
Auto-generated by NarshaMCP plugin with detected engine path.
"""
import subprocess
import sys
from pathlib import Path

def main():
    project_dir = Path(r"../../../../../../Work/Unreal/ProjectBG/")
    project_file = project_dir / (project_dir.name + ".uproject")
    
    if not project_file.exists():
        print(f"Error: Project file not found: {project_file}")
        return 1
    
    # Auto-detected UnrealEditor-Cmd path from FPaths::EngineDir() (platform-aware)
    ue_cmd = r"../../../Engine/Binaries/Win64/UnrealEditor-Cmd.exe"
    
    if not Path(ue_cmd).exists():
        print(f"Error: UnrealEditor-Cmd not found at: {ue_cmd}")
        print("Please verify your Unreal Engine installation")
        return 1
    
    # Execute Commandlet (Issue #183: Startup optimization flags)
    cmd = [
        ue_cmd,
        str(project_file),
        "-run=NarshaMCP.CUBlueprintMetadata",
        "-stdout",
        "-unattended",
        "-nopause",
        "-NoShaderCompile",        # Disable shader compilation (saves ~16s, -18.7%)
        "-nosplash",              # Skip splash screen (saves ~1-2s)
        "-noloadstartuppackages",  # Skip startup content loading (saves ~3-4s)
        "-nologtimes",             # Skip log timestamp formatting (saves ~0.5s)
        "-Multiprocess"             # Enable multiprocessing (parallel asset loading)
    ]
    
    print(f"Executing: {' '.join(cmd)}")
    result = subprocess.run(cmd)
    
    return result.returncode

if __name__ == "__main__":
    sys.exit(main())
